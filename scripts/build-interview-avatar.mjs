/** Build an immutable, losslessly delivered avatar release. No model simplification. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {brotliCompressSync,brotliDecompressSync,constants} from 'node:zlib';
import sharp from 'sharp';
const require=createRequire(import.meta.url);
const {minify}=require('next/dist/compiled/terser');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'public/interview-avatar');
const digest=data=>createHash('sha256').update(data).digest('hex');
async function walk(dir){return(await Promise.all((await fs.readdir(dir,{withFileTypes:true})).map(async e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]))).flat()}
const output=new Map();
for(const folder of ['viewer','licenses'])for(const file of await walk(path.join(source,folder))){let bytes=await fs.readFile(file);if(file.endsWith('.js')){const result=await minify(bytes.toString(),{module:true,compress:{passes:2},mangle:true,format:{comments:/@license|@preserve|^!/}});if(!result.code)throw Error('Empty avatar module');bytes=Buffer.from(result.code)}output.set(path.relative(source,file),bytes)}
const model=await fs.readFile(path.join(source,'Cveat_Office_Avatar_Web.glb'));
output.set('Cveat_Office_Avatar_Web.glb',model);
const br=brotliCompressSync(model,{params:{[constants.BROTLI_PARAM_QUALITY]:11}});
if(!brotliDecompressSync(br).equals(model))throw Error('Avatar transfer compression changed bytes');
output.set('Cveat_Office_Avatar_Web.glb.br',br);
const background=await fs.readFile(path.join(source,'office-background.png'));
const webp=await sharp(background).webp({lossless:true,effort:6}).toBuffer();
const originalPixels=await sharp(background).ensureAlpha().raw().toBuffer(),webpPixels=await sharp(webp).ensureAlpha().raw().toBuffer();
if(!originalPixels.equals(webpPixels))throw Error('Background conversion changed pixels');
output.set('office-background.webp',webp);
output.set('demo-cues.json',await fs.readFile(path.join(source,'demo-cues.json')));
const entries=[...output].sort(([a],[b])=>a.localeCompare(b));
const version=digest(Buffer.from(entries.map(([name,bytes])=>name+':'+digest(bytes)).join('\n'))).slice(0,20);
const destination=path.join(source,'releases',version);await fs.mkdir(destination,{recursive:true});
for(const[name,bytes]of entries){const target=path.join(destination,name);await fs.mkdir(path.dirname(target),{recursive:true});let old;try{old=await fs.readFile(target)}catch{}if(old&&!old.equals(bytes))throw Error('Immutable avatar release mismatch');if(!old)await fs.writeFile(target,bytes)}
const manifest={version,modelSha256:digest(model),backgroundPixelsSha256:digest(originalPixels),lossless:true,files:Object.fromEntries(entries.map(([name,b])=>[name,{bytes:b.length,sha256:digest(b)}]))};
await fs.writeFile(path.join(destination,'asset-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await fs.writeFile(path.join(root,'components/interview/avatar-assets.ts'),`// Generated by scripts/build-interview-avatar.mjs. Do not edit by hand.\nexport const AVATAR_VIEWER_URL = ${JSON.stringify('/interview-avatar/releases/'+version+'/viewer/index.html?embedded=1')};\n`);
console.log(JSON.stringify({avatarRelease:version,modelBytes:model.length,modelBrotliBytes:br.length,backgroundBefore:background.length,backgroundAfter:webp.length,modelUnchanged:true,backgroundPixelsUnchanged:true}));
